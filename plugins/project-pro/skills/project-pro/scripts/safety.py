"""Guided-mode safety net: the items it relies on, warnings when they are dropped, and `scripts/check.sh`."""

from __future__ import annotations

CHECK_SCRIPT_PATH = "scripts/check.sh"
CHECK_COMMAND = f"sh {CHECK_SCRIPT_PATH}"

# (kind, id, plain sentence why it matters). kind: "agents" or "features".
SAFETY_ITEMS: tuple[tuple[str, str, str], ...] = (
    ("agents", "git-security-hooks", "Git hooks stop passwords and keys from being saved into the project history by accident."),
    ("agents", "agent-runtime-hooks", "Runtime hooks stop the AI agent from running dangerous commands or skipping the safety checks."),
    ("agents", "agents-root", "AGENTS.md and the project profile give the agent its rules and let the structure audit run."),
    ("features", "testing-ci", "The test harness and scripts/check.sh are how you know the code works without reading it."),
)

# Order and catalog keys used by check.sh: only keys that exist in the stack's `commands` are emitted.
CHECK_STEPS: tuple[tuple[str, str], ...] = (("lint", "lint"), ("build", "build"), ("test_all", "tests"))

_HEADER = """#!/bin/sh
# Generated by project-pro (guided preset). One command that tells you whether the project is healthy.
# Run it from anywhere:  sh scripts/check.sh
cd "$(dirname "$0")/.." || exit 1

step() {
  sh -c "$2"
  rc=$?
  if [ "$rc" -eq 0 ]; then
    echo "✔ $1 passed"
    return 0
  fi
  if [ "$rc" -eq 127 ]; then
    echo "✘ $1 could not run (a tool it needs is not installed) — ask your agent: \\"install what the check needs\\""
  else
    echo "✘ $1 failed — ask your agent: \\"fix the failing check\\""
  fi
  echo "CHECKS FAILED"
  exit 1
}

"""


def _quote(text: str) -> str:
    return "'" + text.replace("'", "'\\''") + "'"


def safety_warnings(features: list[str], agents: list[str]) -> list[str]:
    """One WARNING line per safety item that the selection dropped (never re-added)."""
    chosen = {"features": set(features), "agents": set(agents)}
    return [f"WARNING: guided mode normally keeps {item}: {why}"
            for kind, item, why in SAFETY_ITEMS if item not in chosen[kind]]


def render_check_script(commands: dict[str, str], skill_script: str) -> str:
    """POSIX sh script running the stack's own catalog commands in order, stopping at the first failure."""
    steps = [f"step {_quote(label)} {_quote(commands[key])}\n" for key, label in CHECK_STEPS if commands.get(key)]
    audit_cmd = 'python3 "' + skill_script + '" audit --target . --fail-on-error'
    audit = (
        f'if [ -f "{skill_script}" ]; then\n'
        f"  step 'structure audit' {_quote(audit_cmd)}\n"
        "else\n"
        '  echo "- structure audit skipped (project-pro was not found at the path used when this project was created)"\n'
        "fi\n"
    )
    return _HEADER + "".join(steps) + audit + 'echo "ALL CHECKS PASSED"\n'


def safety_lines(features: list[str], agents: list[str]) -> list[str]:
    """The enabled safety items, one plain sentence each (used by START_HERE.md and the guided summary)."""
    chosen = {"features": set(features), "agents": set(agents)}
    return [why for kind, item, why in SAFETY_ITEMS if item in chosen[kind]]

