"""Go boundary config: depguard rules for `.golangci.yml`, derived from the chosen architecture.

Syntax source (not guessed): golangci-lint v2.15.0 reference config
  https://github.com/golangci/golangci-lint/blob/v2.15.0/.golangci.reference.yml
  (`version: "2"`, `linters.default/enable`, `linters.settings.depguard.rules.<name>` with `list-mode`,
  `files`, `allow`, `deny: [{pkg, desc}]`, variables `$gostd`/`$test`); docs: https://golangci-lint.run/docs/linters/configuration/
The generated file was run against golangci-lint 2.15.0 (see tests); depguard `pkg` is a string prefix, so the module path is required.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

SOURCE_URL = "https://github.com/golangci/golangci-lint/blob/v2.15.0/.golangci.reference.yml"
DOCS_URL = "https://golangci-lint.run/docs/linters/configuration/"
TOOL_VERSION = "golangci-lint v2.15.0"
CONFIG_NAMES = (".golangci.yml", ".golangci.yaml", ".golangci.toml", ".golangci.json")
LAYERED_ARCHS = {"clean", "modular-clean", "hexagonal"}
MODULE_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._~\-/]*$")


def detect_module(target: Path, explicit: str | None) -> str | None:
    """Module path from `--go-module`, else the `module` line of go.mod; None when unknown (never guessed)."""
    if explicit:
        return explicit if MODULE_RE.match(explicit) else None
    gomod = target / "go.mod"
    if gomod.is_file():
        for line in gomod.read_text(encoding="utf-8", errors="ignore").splitlines():
            m = re.match(r"^\s*module\s+(\S+)\s*$", line)
            if m and MODULE_RE.match(m.group(1).strip('"')):
                return m.group(1).strip('"')
    return None


def _layout(info: dict[str, Any]) -> tuple[list[str], list[str]]:
    dirs = info["scaffold_dirs"]["hexagonal"]
    adapters = [d for d in dirs if d.startswith("internal/adapter/")]
    transport = [d for d in dirs if d.startswith("internal/controller/")]
    return adapters, transport


def _rule(name: str, files: list[str], allow: list[str], deny: list[tuple[str, str]]) -> list[str]:
    out = [f"        {name}:", "          files:"]
    out += [f'            - "{g}"' for g in files]
    if allow:
        out += ["          allow:"] + [f'            - "{a}"' if not a.startswith("$") else f"            - {a}" for a in allow]
    if deny:
        out.append("          deny:")
        for pkg, desc in deny:
            out += [f'            - pkg: "{pkg}"', f'              desc: "{desc}"']
    return out


def depguard_rules(module: str, info: dict[str, Any]) -> list[str]:
    adapters, transport = _layout(info)
    m = module
    std_io = [p.strip('"') for p in info["domain_forbidden_imports"] if p.startswith('"') and "." not in p.strip('"').split("/")[0]]
    domain_deny = [(p, "domain must stay free of transport and I/O packages") for p in std_io]
    lines = _rule("domain", ["**/internal/domain/**", "!$test"], ["$gostd", f"{m}/internal/domain"], domain_deny)
    lines += _rule("usecase", ["**/internal/usecase/**", "!$test"], [], [
        (f"{m}/internal/adapter", "usecase must not import adapters (depend on consumer-owned interfaces)"),
        (f"{m}/internal/controller", "usecase must not import transport"),
    ])
    for adapter in adapters:
        others = [a for a in adapters if a != adapter]
        deny = [(f"{m}/{o}", "adapters must not import each other") for o in others]
        deny += [(f"{m}/internal/controller", "adapters must not import transport")]
        lines += _rule("adapter-" + adapter.rsplit("/", 1)[1], [f"**/{adapter}/**", "!$test"], [], deny)
    for t in transport:
        others = [x for x in transport if x != t]
        deny = [(f"{m}/internal/adapter", "transport must not import adapters; go through usecase")]
        deny += [(f"{m}/{o}", "transport packages must not import each other") for o in others]
        lines += _rule("transport-" + t.rsplit("/", 1)[1], [f"**/{t}/**", "!$test"], [], deny)
    return lines


def _header(arch: str) -> list[str]:
    return [
        f"# Architecture boundary rules ({arch}) generated by project-pro; edit the module path or rules as the layout evolves.",
        f"# Syntax: {TOOL_VERSION} reference config {SOURCE_URL}",
        f"# Docs:   {DOCS_URL}",
        "# `default: standard` keeps golangci-lint's default linters; depguard is added on top (reference config: default = standard|all|none|fast).",
        "# Layers: domain imports only the standard library; usecase must not import adapters or transport;",
        "# adapters must not import each other or transport; transport must not import adapters.",
    ]


def render_full_config(module: str, arch: str, info: dict[str, Any]) -> str:
    body = ["version: \"2\"", "linters:", "  default: standard", "  enable:", "    - depguard", "  settings:", "    depguard:", "      rules:"]
    return "\n".join(_header(arch) + body + depguard_rules(module, info)) + "\n"


def render_snippet(module: str | None, arch: str, info: dict[str, Any]) -> str:
    """Block to merge into an existing config: add `depguard` to `linters.enable` and this under `linters.settings`."""
    body = ["    depguard:", "      rules:"]
    return "\n".join(_header(arch) + body + depguard_rules(module or "<module>", info)) + "\n"


def generate(target: Path, arch: str, info: dict[str, Any], go_module: str | None) -> list[str]:
    if arch not in LAYERED_ARCHS:
        return [f"NOTE: boundary config not yet automated for go + architecture `{arch}` (layered archs only)."]
    module = detect_module(target, go_module)
    existing = next((n for n in CONFIG_NAMES if (target / n).exists()), None)
    if existing:
        snippet = render_snippet(module, arch, info)
        hint = "" if module else " (replace `<module>` with your go.mod module path)"
        return [f"SKIP (exists): {existing}; not modified. Merge this depguard block yourself{hint}:", *("    " + ln for ln in snippet.splitlines())]
    if not module:
        snippet = render_snippet(None, arch, info)
        return ["NOTE: boundary config for go needs the module path (no go.mod, no --go-module); nothing written. "
                "Re-run `init --go-module <path>` or add this to .golangci.yml:", *("    " + ln for ln in snippet.splitlines())]
    (target / ".golangci.yml").write_text(render_full_config(module, arch, info), encoding="utf-8")
    return [f"WRITE: .golangci.yml (depguard boundaries, {TOOL_VERSION} syntax)"]
