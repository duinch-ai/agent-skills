"""Python boundary config: import-linter contracts in `.importlinter` (INI), derived from the chosen architecture.

Syntax source (not guessed): import-linter 2.16 docs (the `stable` docs, release 2.16 of 2026-11-06)
  https://import-linter.readthedocs.io/en/stable/get_started/configure/   (file lookup: setup.cfg, .importlinter, pyproject.toml;
                                                                            `[importlinter]` root_package/include_external_packages)
  https://import-linter.readthedocs.io/en/stable/contract_types/layers/    (`type = layers`, `layers`, `containers`, `a | b` = independent siblings)
  https://import-linter.readthedocs.io/en/stable/contract_types/forbidden/ (`source_modules`, `forbidden_modules`, external packages need include_external_packages)
  https://import-linter.readthedocs.io/en/stable/contract_types/independence/ (`modules`)
Not verified by running `lint-imports`: it was not installed when this was written.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

BASE_URL = "https://import-linter.readthedocs.io/en/stable/"
TOOL_VERSION = "import-linter 2.16 docs"
ROOT_PACKAGE = "src"
LAYER_MODULE = "users"  # the module project-pro scaffolds under src/modules
SHARED_CONFIGS = ("setup.cfg", "pyproject.toml")


def _framework_names(info: dict[str, Any]) -> list[str]:
    names: list[str] = []
    for item in info["domain_forbidden_imports"]:
        m = re.match(r"^(?:import|from)\s+([A-Za-z_][\w]*)", item)
        if m and m.group(1) not in names:
            names.append(m.group(1))
    return names


def _slice_modules(info: dict[str, Any], arch: str) -> list[str]:
    """Slice modules from the scaffold dirs the scaffolder creates for this arch (`src/modules/<name>`), not hard-coded."""
    dirs = info.get("scaffold_dirs", {}).get(arch) or []
    return [d.replace("/", ".") for d in dirs if re.fullmatch(rf"{ROOT_PACKAGE}/modules/[A-Za-z_]\w*", d)]


def _contracts(arch: str, info: dict[str, Any]) -> list[str] | None:
    base = f"{ROOT_PACKAGE}.modules.{LAYER_MODULE}"
    if arch == "hexagonal":
        return [
            "[importlinter:contract:layers]",
            "name = Hexagonal layers (entrypoints | adapters -> application -> domain)",
            "type = layers",
            "layers =",
            f"    {base}.entrypoints | {base}.adapters",
            f"    {base}.application",
            f"    {base}.domain",
            "",
            "[importlinter:contract:domain-pure]",
            "name = Domain imports no framework or I/O library",
            "type = forbidden",
            f"source_modules = {base}.domain",
            "forbidden_modules =",
            *(f"    {n}" for n in _framework_names(info)),
        ]
    if arch == "vertical-slice":
        slices = _slice_modules(info, arch)
        if len(slices) < 2:
            return None
        return [
            "[importlinter:contract:slices]",
            "name = Feature slices are independent",
            "type = independence",
            "modules =",
            *(f"    {m}" for m in slices),
            "",
            "[importlinter:contract:shared-is-foundation]",
            "name = shared code does not import feature slices",
            "type = forbidden",
            f"source_modules = {ROOT_PACKAGE}.shared",
            f"forbidden_modules = {ROOT_PACKAGE}.modules",
        ]
    return None


def render_config(arch: str, info: dict[str, Any]) -> str | None:
    contracts = _contracts(arch, info)
    if contracts is None:
        return None
    head = [
        f"# Architecture boundary contracts ({arch}) generated by project-pro; run with `lint-imports` (pip install import-linter).",
        f"# Syntax: {TOOL_VERSION}: {BASE_URL}get_started/configure/ , {BASE_URL}contract_types/layers/ ,",
        f"#         {BASE_URL}contract_types/forbidden/ , {BASE_URL}contract_types/independence/",
        "# Slice modules in the independence contract come from the project's scaffold dirs (src/modules/<name>), not a fixed list.",
        f"# Assumes imports are written as `{ROOT_PACKAGE}.<...>`; change root_package if your code imports `modules.<...>`.",
        "[importlinter]",
        f"root_package = {ROOT_PACKAGE}",
        "include_external_packages = True",
        "",
    ]
    return "\n".join(head + contracts) + "\n"


def _has_existing(target: Path) -> str | None:
    if (target / ".importlinter").exists():
        return ".importlinter"
    for name in SHARED_CONFIGS:
        p = target / name
        if p.is_file() and "importlinter" in p.read_text(encoding="utf-8", errors="ignore"):
            return name
    return None


def generate(target: Path, arch: str, info: dict[str, Any]) -> list[str]:
    text = render_config(arch, info)
    if text is None:
        return [f"NOTE: boundary config not yet automated for python + architecture `{arch}`."]
    existing = _has_existing(target)
    if existing:
        return [f"SKIP (exists): {existing} already has import-linter config; not modified. Suggested contracts:",
                *("    " + ln for ln in text.splitlines())]
    (target / ".importlinter").write_text(text, encoding="utf-8")
    return ["WRITE: .importlinter (import-linter contracts, INI format)"]
